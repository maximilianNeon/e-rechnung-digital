// Inlines the PDF/A fonts and colour profile as base64, so the same code runs
// in the browser, in tests and in the MCP bundles without file loaders.
import { readFile, writeFile } from "node:fs/promises";

const dir = new URL("../src/assets/pdf/", import.meta.url);
const b64 = async (name) => (await readFile(new URL(name, dir))).toString("base64");

const out = `// Generated by scripts/pdf-assets.mjs from src/assets/pdf. Do not edit.
export const GEIST_REGULAR = "${await b64("Geist-Regular.ttf")}";
export const GEIST_BOLD = "${await b64("Geist-Bold.ttf")}";
export const SRGB_ICC = "${await b64("sRGB.icc")}";
`;
await writeFile(new URL("../src/lib/pdfAssets.ts", import.meta.url), out);
console.log(`pdfAssets.ts: ${out.length} bytes`);
