import { fileURLToPath } from "node:url";
import { build } from "esbuild";

// zugferd-ts is bundled from the site's node_modules, which carries the
// namespace fix in ../patches. Everything else stays a runtime dependency.
const patchedZugferd = fileURLToPath(
  new URL("../node_modules/zugferd-ts/dist/index.js", import.meta.url),
);

const patchedZugferdPlugin = {
  name: "patched-zugferd",
  setup(b) {
    b.onResolve({ filter: /^zugferd-ts$/ }, () => ({ path: patchedZugferd }));
  },
};

// Hosted endpoint for ChatGPT and Claude.ai, served by Vercel as /api/mcp.
// Committed to the repo because Vercel detects functions before the build runs.
await build({
  entryPoints: ["src/remote.ts"],
  outfile: "../api/mcp.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  external: ["@modelcontextprotocol/sdk", "zod", "pdf-lib", "happy-dom", "xmlbuilder2"],
  plugins: [patchedZugferdPlugin],
  banner: { js: "// Generated by mcp/build.mjs from mcp/src/remote.ts. Do not edit." },
  logLevel: "info",
});

await build({
  entryPoints: ["src/index.ts"],
  outfile: "dist/index.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  external: ["@modelcontextprotocol/sdk", "zod", "pdf-lib", "happy-dom", "xmlbuilder2"],
  plugins: [patchedZugferdPlugin],
  logLevel: "info",
});
